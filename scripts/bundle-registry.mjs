#!/usr/bin/env node
/**
 * Bake the textbook registry into the deployment (DESIGN §2b).
 *
 * Resolves the registry ref to a commit SHA, fetches registry.json *at that SHA*,
 * validates it, and writes registry/bundled.mjs, which the handler imports. The
 * function never fetches the registry at runtime.
 *
 * Runs as Vercel's build step (`vercel-build`, followed by the test suite), so a
 * registry that fails validation or breaks a test never deploys, and the previous
 * deployment stays live. Also run it by hand to refresh the committed snapshot:
 *
 *   npm run registry:bundle                     # latest main
 *   REGISTRY_REF=<40-char sha> npm run registry:bundle   # pin
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { validateRegistry } from '../lib/registry.mjs';

const REGISTRY_REPO = 'textbookproject2026-alt/textbook-registry';
const FETCH_TIMEOUT_MS = 15000;
const OUT = fileURLToPath(new URL('../registry/bundled.mjs', import.meta.url));

function fail(message) {
  console.error(`bundle-registry: ${message}`);
  process.exit(1);
}

function resolveSha(ref) {
  if (/^[0-9a-f]{40}$/.test(ref)) return ref;
  // git ls-remote, not the REST API: build machines share IPs, and the unauthenticated
  // API limit (60/hour per IP) would fail builds at random.
  let out;
  try {
    out = execFileSync('git', ['ls-remote', `https://github.com/${REGISTRY_REPO}.git`, `refs/heads/${ref}`], {
      encoding: 'utf8',
      timeout: FETCH_TIMEOUT_MS,
    });
  } catch (err) {
    fail(`git ls-remote failed for ${REGISTRY_REPO} ${ref}: ${err.message}`);
  }
  const sha = out.split(/\s+/)[0];
  if (!/^[0-9a-f]{40}$/.test(sha ?? '')) fail(`branch ${ref} not found on ${REGISTRY_REPO}`);
  return sha;
}

const ref = process.env.REGISTRY_REF || 'main';
const sha = resolveSha(ref);
const url = `https://raw.githubusercontent.com/${REGISTRY_REPO}/${sha}/registry.json`;

let res;
try {
  res = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
} catch (err) {
  fail(`could not fetch ${url}: ${err.message}`);
}
if (!res.ok) fail(`${url} returned ${res.status}`);

let registry;
try {
  registry = JSON.parse(await res.text());
} catch {
  fail(`${url} is not valid JSON`);
}

try {
  validateRegistry(registry);
} catch (err) {
  fail(err.message);
}

const bundle = { sha, source: `https://github.com/${REGISTRY_REPO}/blob/${sha}/registry.json`, registry };
writeFileSync(
  OUT,
  `// GENERATED by scripts/bundle-registry.mjs. Do not edit by hand: change the registry repo and rebuild.\n` +
    `export default ${JSON.stringify(bundle, null, 2)};\n`,
);
console.log(`bundle-registry: ${REGISTRY_REPO}@${sha} (${ref}), ${registry.books.length} book(s) -> registry/bundled.mjs`);
